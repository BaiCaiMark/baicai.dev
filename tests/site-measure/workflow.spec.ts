test('canvas direct dimension selection, pan, zoom and fit leave geometry untouched', async ({ page }) => {
  await sample(page); await bathroom(page)
  const before = await backup(page, 'before-pan.json')
  await page.locator('[data-param=width]').click()
  await expect(width(page)).toBeFocused()
  const canvas = page.locator('svg.sm-canvas'); await canvas.scrollIntoViewIfNeeded(); const box = (await canvas.boundingBox())!
  const view = await canvas.getAttribute('viewBox')
  await page.mouse.move(box.x + box.width * 0.8, box.y + box.height * 0.8)
  await page.mouse.down(); await page.mouse.move(box.x + box.width * 0.7, box.y + box.height * 0.7, { steps: 6 }); await page.mouse.up()
  await expect(canvas).not.toHaveAttribute('viewBox',view!)
  await page.getByRole('button', { name: '放大', exact: true }).click()
  await page.getByRole('button', { name: 'Fit All', exact: true }).click()
  expect(await canvas.getAttribute('viewBox')).toBe(view)
  const after = await backup(page, 'after-pan.json')
  expect(after.areas).toEqual(before.areas)
})
test('two-finger browser touch changes viewport only', async ({ page, context }) => {
  await sample(page); await bathroom(page)
  const canvas=page.locator('svg.sm-canvas'),b=(await canvas.boundingBox())!
  await canvas.scrollIntoViewIfNeeded()
  const r=(await canvas.boundingBox())!, x=r.x+r.width/2,y=r.y+r.height/2
  const view=await canvas.getAttribute('viewBox')
  const session=await context.newCDPSession(page)
  const touches=(distance:number)=>[{x:x-distance,y,id:0},{x:x+distance,y,id:1}]
  await session.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:touches(50)})
  await session.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:touches(100)})
  await session.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]})
  await expect(canvas).not.toHaveAttribute('viewBox',view!)
  await expect(width(page)).toHaveValue('59')
  expect(b.width).toBeGreaterThan(0)
})
