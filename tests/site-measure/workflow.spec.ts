async function bathroom(page: Page) { await page.getByRole('button', { name: 'Bathroom 1 1', exact: true }).click() }
async function backup(page: Page, file: string) {
  const waiting = page.waitForEvent('download')
  await page.getByRole('button', { name: '工程備份', exact: true }).click()
  const download = await waiting
  await download.saveAs(path.join(root, file))
  return JSON.parse(fs.readFileSync(path.join(root, file), 'utf8'))
}
