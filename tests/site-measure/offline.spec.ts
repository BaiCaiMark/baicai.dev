import { test, expect } from '@playwright/test'

test('installed Site Measure can reopen a saved project without internet', async ({ page, context }) => {
  await page.goto('/tools/site-measure')
  await expect(page.getByTestId('sm-offline-state')).toHaveText('Offline ready', { timeout: 45000 })
  await page.getByRole('button', { name: 'New project', exact: true }).click()
  await page.getByRole('textbox', { name: 'Project name' }).fill('Offline field inspection')
  await expect(page.locator('.sm-save-state')).toHaveText('Saved in this browser')
  await context.setOffline(true)
  await page.reload({ waitUntil: 'domcontentloaded' })
  await expect(page.getByRole('heading', { name: 'Site Measure Studio' })).toBeVisible()
  await expect(page.getByRole('button', { name: /Offline field inspection/ })).toBeVisible()
  await page.getByRole('button', { name: /Offline field inspection/ }).click()
  await expect(page.getByRole('textbox', { name: 'Project name' })).toHaveValue('Offline field inspection')
  await page.getByRole('textbox', { name: 'Project name' }).fill('Offline field inspection saved')
  await expect(page.locator('.sm-save-state')).toHaveText('Saved in this browser')
  await page.reload({ waitUntil: 'domcontentloaded' })
  await page.getByRole('button', { name: /Offline field inspection saved/ }).click()
  await expect(page.getByRole('textbox', { name: 'Project name' })).toHaveValue('Offline field inspection saved')
  await context.setOffline(false)
})

test('cached sample can export PDF and DXF while disconnected', async ({ page, context }) => {
  await page.goto('/tools/site-measure')
  await expect(page.getByTestId('sm-offline-state')).toHaveText('Offline ready', { timeout: 45000 })
  await page.getByRole('button', { name: 'Try sample Kitchen', exact: true }).click()
  await expect(page.locator('.sm-save-state')).toHaveText('Saved in this browser')
  await context.setOffline(true)
  await page.reload({ waitUntil: 'domcontentloaded' })
  await page.getByRole('button', { name: /Sample Kitchen & Vanities/ }).click()
  await page.getByRole('button', { name: 'Export', exact: true }).click()
  const pdf = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export PDF' }).click()
  expect((await pdf).suggestedFilename()).toMatch(/\.pdf$/)
  const dxf = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export DXF' }).click()
  expect((await dxf).suggestedFilename()).toMatch(/\.dxf$/)
  await context.setOffline(false)
})
