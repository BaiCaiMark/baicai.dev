import { test, expect } from '@playwright/test'
import fs from 'node:fs/promises'

test('rename an existing Room inline, preserve its Parts, then save and reopen', async ({page}) => {
  await page.setViewportSize({width:390,height:844})
  await page.goto('/tools/site-measure')
  await page.getByRole('button',{name:'Try sample Kitchen',exact:true}).click()
  const canvas=page.locator('svg.sm-canvas')
  await expect(canvas.locator('[data-shape]')).toHaveCount(5)

  await page.getByRole('button',{name:'Workspace menu'}).click()
  await page.getByRole('button',{name:'Rename room Bathroom 1'}).click()
  const form=page.getByRole('form',{name:'Rename room Bathroom 1'})
  await expect(form.getByRole('textbox',{name:'Room name'})).toHaveValue('Bathroom 1')
  await form.getByRole('textbox',{name:'Room name'}).fill('Master Ensuite')
  await form.getByRole('button',{name:'Save',exact:true}).click()
  await expect(page.getByRole('button',{name:'Rename room Master Ensuite'})).toBeVisible()
  await expect(canvas.locator('[data-shape]')).toHaveCount(5)

  const download=page.waitForEvent('download')
  await page.getByRole('button',{name:'Download project backup'}).click()
  const file=await download
  const backup=JSON.parse(await fs.readFile(await file.path(),'utf8'))
  expect(backup.areas[1].name).toBe('Master Ensuite')
  expect(backup.areas[1].shapes[0].name).toBe('Vanity 59 + 1')
  expect(backup.areas[1].shapes[0].dimensions.width.input).toBe('59')

  await expect(page.locator('.sm-save-state')).toHaveText('Saved in this browser')
  await page.reload()
  await page.locator('.sm-recent button').first().click()
  await page.getByRole('button',{name:'Workspace menu'}).click()
  await expect(page.getByRole('button',{name:'Rename room Master Ensuite'})).toBeVisible()
  await expect(page.locator('svg.sm-canvas [data-shape]')).toHaveCount(5)
})

test('new Area offers immediate naming; cancel, duplicate and empty names are safe', async ({page}) => {
  await page.setViewportSize({width:390,height:844})
  await page.goto('/tools/site-measure')
  await page.getByRole('button',{name:'New project',exact:true}).click()
  await page.getByRole('button',{name:'Workspace menu'}).click()
  await page.getByRole('button',{name:'＋ Area'}).click()
  const form=page.getByRole('form',{name:'Rename room Area 2'})
  const input=form.getByRole('textbox',{name:'Room name'})
  await expect(input).toHaveValue('Area 2')
  await input.fill('Kitchen')
  await form.getByRole('button',{name:'Save'}).click()
  await expect(form.getByRole('alert')).toContainText('already exists')
  await input.fill('   ')
  await form.getByRole('button',{name:'Save'}).click()
  await expect(form.getByRole('alert')).toContainText('cannot be empty')
  await input.fill('Guest Bathroom')
  await input.press('Enter')
  await expect(page.getByRole('button',{name:'Guest Bathroom',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Rename room Guest Bathroom'}).click()
  const again=page.getByRole('form',{name:'Rename room Guest Bathroom'})
  await again.getByRole('textbox',{name:'Room name'}).fill('Cancelled Name')
  await again.getByRole('textbox',{name:'Room name'}).press('Escape')
  await expect(page.getByRole('button',{name:'Guest Bathroom',exact:true})).toBeVisible()
  await expect(page.getByRole('button',{name:'Cancelled Name',exact:true})).toHaveCount(0)
  await page.getByRole('button',{name:'Guest Bathroom',exact:true}).click()
  await page.getByRole('button',{name:'Add a part'}).click()
  await page.getByRole('group',{name:'Add a part'}).getByRole('button',{name:'＋ Rectangle'}).click()
  await expect(page.locator('svg.sm-canvas [data-shape] .sm-part-title')).toHaveText('Guest Bathroom 1')
})
