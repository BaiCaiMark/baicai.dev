import { test, expect } from '@playwright/test'

test('mobile workspace keeps canvas controls hidden and fit is reachable by double-tap',async({page})=>{
  await page.setViewportSize({width:390,height:844})
  await page.goto('/tools/site-measure')
  await page.getByRole('button',{name:'New project',exact:true}).click()
  const canvas=page.locator('.sm-canvas')
  await expect(canvas).toBeVisible()
  await expect(page.locator('.sm-canvas-tools')).toHaveCount(0)
  await expect(page.getByRole('button',{name:'Zoom in'})).toHaveCount(0)
  await expect(page.getByRole('button',{name:'Zoom out'})).toHaveCount(0)
  const fitted=await canvas.getAttribute('viewBox')
  const rect=await canvas.boundingBox()
  expect(rect).not.toBeNull()
  const x=rect!.x+rect!.width*.45,y=rect!.y+rect!.height*.61
  await page.mouse.move(x,y)
  await page.mouse.down()
  await page.mouse.move(x+64,y+42,{steps:6})
  await page.mouse.up()
  await expect.poll(()=>canvas.getAttribute('viewBox')).not.toBe(fitted)
  await page.touchscreen.tap(x+64,y+42)
  await page.touchscreen.tap(x+64,y+42)
  await expect.poll(()=>canvas.getAttribute('viewBox')).toBe(fitted)
  await page.getByRole('button',{name:'Workspace menu'}).click()
  await expect(page.getByRole('button',{name:/Snap · On/})).toHaveAttribute('aria-pressed','true')
  await expect(page.getByRole('button',{name:/Ortho · Off/})).toHaveAttribute('aria-pressed','false')
  await page.getByRole('button',{name:/Snap · On/}).click()
  await expect(page.getByRole('button',{name:/Snap · Off/})).toHaveAttribute('aria-pressed','false')
  await page.getByRole('button',{name:/Snap · Off/}).click()
  await page.getByRole('button',{name:/Ortho · Off/}).click()
  await expect(page.getByRole('button',{name:/Ortho · On/})).toHaveAttribute('aria-pressed','true')
  await page.getByRole('button',{name:/Ortho · On/}).click()
  await expect(page.getByRole('button',{name:/Snap · On/})).toHaveAttribute('aria-pressed','true')
})

test('fit from workspace menu resets moved canvas without adding a persistent toolbar',async({page})=>{
  await page.setViewportSize({width:800,height:1100})
  await page.goto('/tools/site-measure')
  await page.getByRole('button',{name:'New project',exact:true}).click()
  await page.getByRole('button',{name:'Add a part'}).click()
  await page.getByRole('group',{name:'Add a part'}).getByRole('button',{name:'＋ Rectangle'}).click()
  const canvas=page.locator('.sm-canvas')
  const fitted=await canvas.getAttribute('viewBox')
  const rect=await canvas.boundingBox()
  expect(rect).not.toBeNull()
  // Empty space to the lower-right of the template.
  const x=rect!.x+rect!.width*.87,y=rect!.y+rect!.height*.87
  await page.mouse.move(x,y)
  await page.mouse.down()
  await page.mouse.move(x-80,y-60,{steps:5})
  await page.mouse.up()
  await expect.poll(()=>canvas.getAttribute('viewBox')).not.toBe(fitted)
  await page.getByRole('button',{name:'Workspace menu'}).click()
  await page.getByRole('button',{name:/Fit All · double-tap/}).click()
  await expect.poll(()=>canvas.getAttribute('viewBox')).toBe(fitted)
  await expect(page.locator('.sm-canvas-tools')).toHaveCount(0)
})
