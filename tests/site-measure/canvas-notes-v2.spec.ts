import {test, expect, type Page} from '@playwright/test'
import fs from 'node:fs/promises'

async function backup(page:Page){
  await page.getByRole('button',{name:'Workspace menu'}).click()
  const wait=page.waitForEvent('download')
  await page.getByRole('button',{name:'Download project backup'}).click()
  const file=await wait
  return JSON.parse(await fs.readFile(await file.path(),'utf8'))
}
async function addNoteAtCenter(page:Page) {
  await page.getByRole('button',{name:'Add a part'}).click()
  await page.getByRole('group',{name:'Add a part'}).getByRole('button',{name:'＋ Note · field annotation'}).click()
  await expect(page.getByText(/Tap the drawing to point your note here/)).toBeVisible()
  const b=(await page.locator('svg.sm-canvas').boundingBox())!
  await page.touchscreen.tap(b.x+b.width*.45,b.y+b.height*.56)
  await expect(page.getByRole('form',{name:'New canvas note'})).toBeVisible()
}
test('P5.1 phone: add an unassigned Canvas Note, edit its text, move the label, undo, save and reopen',async({page})=>{
  await page.setViewportSize({width:390,height:844})
  await page.goto('/tools/site-measure')
  await page.getByRole('button',{name:'New project',exact:true}).click()
  await addNoteAtCenter(page)
  const form=page.getByRole('form',{name:'New canvas note'})
  await form.getByRole('textbox',{name:'Canvas note text'}).fill('Wall not straight. Verify 1/4″ at the back.')
  await form.getByRole('button',{name:'Save'}).click()
  const card=page.locator('[data-canvas-note]')
  await expect(card).toHaveCount(1)
  await expect(card.locator('.sm-canvas-note-leader')).toHaveCount(1)
  await page.screenshot({path:'artifacts/site-measure/p5-note-mobile.png',fullPage:true})
  const before=await backup(page)
  const note=before.canvasNotes[0]
  expect(before.areas[0].shapes).toHaveLength(0)
  expect(note.text).toContain('Wall not straight')
  const move=await card.locator('.sm-canvas-note-card rect').evaluate(el=>{
    const r=el as SVGRectElement,m=r.getScreenCTM()!
    const q=new DOMPoint(50,28).matrixTransform(m)
    return{x:q.x,y:q.y}
  })
  await page.mouse.move(move.x,move.y)
  await page.mouse.down()
  await page.mouse.move(move.x-50,move.y+58,{steps:8})
  await page.mouse.up()
  const moved=await backup(page)
  expect(moved.canvasNotes[0].x).not.toBe(note.x)
  expect(moved.canvasNotes[0].targetX).toBe(note.targetX)
  expect(moved.canvasNotes[0].targetY).toBe(note.targetY)
  await page.getByRole('button',{name:'Undo',exact:true}).click()
  const undone=await backup(page)
  expect(undone.canvasNotes[0].x).toBe(note.x)
  await page.getByRole('button',{name:/Edit canvas note/}).first().press('Enter')
  const edit=page.getByRole('form',{name:'Edit canvas note'})
  await edit.getByRole('textbox',{name:'Canvas note text'}).fill('Check wall before cutting')
  await edit.getByRole('button',{name:'Save'}).click()
  await expect(card.locator('.sm-canvas-note-card')).toHaveAttribute('aria-label','Edit canvas note Check wall before cutting')
  await expect(page.locator('.sm-save-state')).toHaveText('Saved in this browser')
  await page.reload()
  await page.locator('.sm-recent button').first().click()
  await expect(page.locator('[data-canvas-note] .sm-canvas-note-card')).toHaveAttribute('aria-label','Edit canvas note Check wall before cutting')
  await expect(page.locator('svg.sm-canvas [data-shape]')).toHaveCount(0)
})
test('P5.1 pin retarget, cancel and delete never fabricate dimensions',async({page})=>{
  await page.goto('/tools/site-measure')
  await page.getByRole('button',{name:'New project',exact:true}).click()
  await page.getByRole('button',{name:'Add a part'}).click()
  await page.getByRole('group',{name:'Add a part'}).getByRole('button',{name:'＋ Rectangle'}).click()
  const initial=await backup(page)
  await addNoteAtCenter(page)
  await page.getByRole('form',{name:'New canvas note'}).getByRole('button',{name:'Cancel'}).click()
  expect((await backup(page)).canvasNotes).toHaveLength(0)
  await addNoteAtCenter(page)
  await page.getByRole('form',{name:'New canvas note'}).getByRole('textbox',{name:'Canvas note text'}).fill('Verify sink center')
  await page.getByRole('form',{name:'New canvas note'}).getByRole('button',{name:'Save'}).click()
  const note=page.locator('[data-canvas-note]')
  await note.locator('.sm-canvas-note-card').press('Enter')
  await page.getByRole('form',{name:'Edit canvas note'}).getByRole('button',{name:'Move pin'}).click()
  const b=(await page.locator('svg.sm-canvas').boundingBox())!
  await page.touchscreen.tap(b.x+b.width*.65,b.y+b.height*.30)
  const moved=await backup(page)
  expect(moved.canvasNotes).toHaveLength(1)
  expect(moved.canvasNotes[0].targetX).not.toBe(initial.canvasNotes?.[0]?.targetX)
  expect(moved.areas[0].shapes[0].dimensions).toEqual(initial.areas[0].shapes[0].dimensions)
  expect(moved.areas[0].shapes[0].allowances).toEqual(initial.areas[0].shapes[0].allowances)
  await note.locator('.sm-canvas-note-card').press('Enter')
  await page.getByRole('form',{name:'Edit canvas note'}).getByRole('button',{name:'Delete'}).click()
  await expect(page.locator('[data-canvas-note]')).toHaveCount(0)
  await page.getByRole('button',{name:'Undo',exact:true}).click()
  await expect(page.locator('[data-canvas-note]')).toHaveCount(1)
  await page.getByRole('button',{name:'Workspace menu'}).click()
  await page.getByRole('button',{name:'PDF / DXF Export'}).click()
  await expect(page.locator('.sm-export-panel')).toContainText('Canvas Notes are saved in the project backup')
})
