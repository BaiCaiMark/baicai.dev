import {test,expect} from '@playwright/test'

test('DXF-derived bathroom step starts as unmeasured guide; real dimensions drive the geometry',async({page})=>{
  await page.goto('/tools/site-measure')
  await page.getByRole('button',{name:'New project',exact:true}).click()
  await page.locator('.sm-template-picker summary').click()
  await page.getByRole('button',{name:'Deep Right',exact:true}).click()
  const panel=page.locator('.sm-quick-panel')
  await expect(panel).toBeVisible()
  await expect(panel).toContainText('Stepped Vanity · Deep Right')
  await expect(page.locator('path.sm-template-guide')).toHaveCount(1)
  await expect(page.locator('path.sm-top')).toHaveCount(0)
  await expect(panel).toContainText('Enter actual Cabinet measurements')
  await panel.getByRole('textbox',{name:'Total length'}).fill('70')
  await panel.getByRole('textbox',{name:'Max depth'}).fill('22 1/2')
  await panel.getByRole('textbox',{name:'Shallow depth'}).fill('7')
  await panel.getByRole('textbox',{name:'Deep section width'}).fill('40')
  await expect(page.locator('path.sm-top')).toHaveCount(1)
  await expect(panel.locator('.sm-quick-final')).toContainText('70″ × 22.5″')
  await panel.getByRole('button',{name:'Deep Left',exact:true}).click()
  await expect(panel).toContainText('Stepped Vanity · Deep Left')
  await expect(page.locator('.sm-save-state')).toHaveText('Saved in this browser')
  const download=page.waitForEvent('download')
  await page.getByRole('button',{name:'Backup',exact:true}).click()
  const file=await download
  const fs=await import('node:fs/promises')
  const raw=JSON.parse(await fs.readFile(await file.path() as string,'utf8'))
  const shape=raw.areas[0].shapes[0]
  expect(shape.template).toBe('l')
  expect(shape.profile).toBe('vanity-step')
  expect(shape.mirrored).toBe(false)
  expect(shape.dimensions.width.input).toBe('70')
  expect(shape.references).toHaveLength(0)
  expect(shape.treatments).toBeUndefined()
  await page.reload()
  await page.locator('.sm-recent button').first().click()
  await expect(page.locator('path.sm-top')).toHaveCount(1)
  await expect(page.locator('.sm-part-strip')).toContainText('Vanity Step')
})

test('both deep-side templates can be selected without drawing a six-edge contour',async({page})=>{
  await page.goto('/tools/site-measure')
  await page.getByRole('button',{name:'New project',exact:true}).click()
  await page.locator('.sm-template-picker summary').click()
  await page.getByRole('button',{name:'Deep Left',exact:true}).click()
  await expect(page.locator('path.sm-template-guide')).toHaveCount(1)
  await page.locator('.sm-template-picker summary').click()
  await page.locator('.sm-template-picker-options').getByRole('button',{name:'Deep Right',exact:true}).click()
  await expect(page.locator('path.sm-template-guide')).toHaveCount(2)
  await expect(page.locator('path.sm-top')).toHaveCount(0)
  await expect(page.locator('.sm-part-strip')).toContainText('Deep Left')
  await expect(page.locator('.sm-part-strip')).toContainText('Deep Right')
})
