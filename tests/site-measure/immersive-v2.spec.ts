import {test,expect} from '@playwright/test'

test('phone workspace owns viewport and exposes on-demand tools',async({page})=>{
  await page.setViewportSize({width:390,height:844})
  await page.goto('/tools/site-measure')
  await page.getByRole('button',{name:'New project',exact:true}).click()
  await expect(page.locator('.sm-studio')).toHaveAttribute('data-immersive','true')
  await expect(page.locator('.site-header')).toBeHidden()
  await expect(page.locator('.site-footer')).toBeHidden()
  await expect(page.locator('.sm-heading')).toBeHidden()
  await expect(page.locator('.sm-canvas')).toBeVisible()
  const viewport=await page.locator('.sm-canvas').boundingBox()
  expect(viewport).not.toBeNull()
  expect(Math.abs(viewport!.width-390)).toBeLessThan(2)
  expect(Math.abs(viewport!.height-844)).toBeLessThan(3)
  expect(await page.evaluate(()=>getComputedStyle(document.documentElement).overflow)).toBe('hidden')
  await page.getByRole('button',{name:'Add a part',exact:true}).click()
  await page.getByRole('group',{name:'Add a part'}).getByRole('button',{name:'＋ Rectangle'}).click()
  await expect(page.locator('[data-shape]')).toHaveCount(1)
  await page.locator('[data-edge="back"] [data-dimension]').first().press('Enter')
  await expect(page.locator('.sm-dimension-editor')).toBeVisible()
  await page.getByRole('button',{name:'Close dimension editor'}).click()
  await page.getByRole('button',{name:'Workspace menu'}).click()
  await page.getByRole('button',{name:'PDF / DXF Export'}).click()
  await expect(page.getByRole('button',{name:'Export PDF'})).toBeVisible()
  await page.getByRole('button',{name:'Back to projects'}).click()
  await expect(page.locator('.sm-studio')).toHaveAttribute('data-immersive','false')
  await expect(page.locator('.site-header')).toBeVisible()
  await expect(page.getByRole('button',{name:/Enter Workspace/})).toBeVisible()
})

test('tablet full workspace retains canvas coordinate space with floating controls',async({page})=>{
  await page.setViewportSize({width:800,height:1100})
  await page.goto('/tools/site-measure')
  await page.getByRole('button',{name:'New project',exact:true}).click()
  const rect=await page.locator('.sm-canvas').boundingBox()
  expect(rect).not.toBeNull()
  expect(Math.abs(rect!.width-800)).toBeLessThan(2)
  expect(Math.abs(rect!.height-1100)).toBeLessThan(3)
  await page.getByRole('button',{name:'Add a part',exact:true}).click()
  await page.getByRole('group',{name:'Add a part'}).getByRole('button',{name:'＋ Rectangle'}).click()
  await page.getByRole('button',{name:'Part actions'}).click()
  await expect(page.getByRole('toolbar',{name:'Selected part actions'})).toBeVisible()
  await page.getByRole('button',{name:'Part actions'}).click()
  await expect(page.getByRole('toolbar',{name:'Selected part actions'})).toHaveCount(0)
})
