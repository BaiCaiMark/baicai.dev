import { test, expect, type Page } from '@playwright/test'
import fs from 'node:fs/promises'

async function dimension(page:Page,edge:string,text:string) {
  await page.locator('[data-edge="'+edge+'"] [data-dimension]').press('Enter')
  await page.getByRole('textbox',{name:'Cabinet size'}).fill(text)
  await page.getByRole('button',{name:'Close dimension editor'}).click()
}
async function openPart(page:Page,name:string) {
  await page.goto('/tools/site-measure')
  await page.getByRole('button',{name:'New project',exact:true}).click()
  await page.getByRole('button',{name:'Add a part'}).click()
  await page.getByRole('group',{name:'Add a part'}).getByRole('button',{name,exact:true}).click()
}
test('Island single sink reading recomputes on both sides and survives backup and reload',async({page})=>{
  await page.setViewportSize({width:1024,height:700})
  await openPart(page,'＋ Island')
  await dimension(page,'back','116 1/4')
  await dimension(page,'right','38')
  await page.getByRole('button',{name:'Part actions'}).click()
  await page.getByRole('toolbar',{name:'Selected part actions'}).getByRole('button',{name:'＋ Sink',exact:true}).click()
  const input=page.getByRole('textbox',{name:'Sink Center distance'})
  await input.fill('71 9/16')
  await expect(page.getByLabel('Sink reference basis')).toHaveValue('cabinet')
  await page.setViewportSize({width:1024,height:370})
  const box=await input.boundingBox()
  expect(box!.y+box!.height).toBeLessThan(370)
  await input.press('Enter')
  await page.setViewportSize({width:1024,height:700})
  await expect(page.locator('.sm-sink-chain')).toContainText('72 9/16″')
  await page.locator('[data-edge="back"] [data-dimension]').press('Enter')
  for(const side of ['Left','Right']){
    await page.getByRole('textbox',{name:side+' overhang'}).fill('3/4')
    await expect(page.locator('[data-edge="'+side.toLowerCase()+'"]')).toHaveAttribute('data-selected','true')
  }
  await page.getByRole('button',{name:'Close dimension editor'}).click()
  await expect(page.locator('[data-edge="back"] .sm-edge-value')).toHaveText('117 3/4″')
  await expect(page.locator('.sm-sink-chain')).toContainText('72 5/16″')
  await page.locator('[data-edge="left"]').press('Enter')
  await page.getByRole('button',{name:'Wall',exact:true}).click()
  await expect(page.getByRole('textbox',{name:'Left overhang'})).toHaveCount(0)
  await expect(page.locator('.sm-direct-editor')).toContainText('Stored overhang 3/4″')
  await page.getByRole('button',{name:'OPEN',exact:true}).click()
  await expect(page.getByRole('textbox',{name:'Left overhang'})).toHaveValue('3/4')
  await page.getByRole('button',{name:'Close direct editor'}).click()
  await page.getByRole('button',{name:'Workspace menu'}).click()
  const download=page.waitForEvent('download')
  await page.getByRole('button',{name:'Download project backup'}).click()
  const backup=JSON.parse(await fs.readFile((await (await download).path())!,'utf8'))
  expect(backup.areas[0].shapes[0].references[0]).toMatchObject({fromX:'left',basis:'cabinet',x:{input:'71 9/16'},y:{input:''}})
  await page.getByRole('button',{name:'Workspace menu'}).click()
  await expect(page.locator('.sm-v2-status')).toContainText('Saved in this browser')
  await page.reload()
  await page.locator('.sm-recent button').first().click()
  await expect(page.locator('.sm-sink-chain')).toContainText('72 5/16″')
})

test('incomplete L lower arm and notch use the same inside edge as the final outline',async({page})=>{
  await openPart(page,'＋ L-shape')
  await page.locator('[data-edge="front"] [data-dimension]').press('Enter')
  await page.getByRole('textbox',{name:'Cabinet size'}).fill('24')
  await page.getByRole('textbox',{name:'Inside overhang'}).fill('1.5')
  await expect(page.locator('.sm-dimension-result')).toContainText('25 1/2″')
  await page.getByRole('button',{name:'Close dimension editor'}).click()
  await dimension(page,'back','60')
  await expect(page.locator('[data-edge="innerX"] .sm-edge-value')).toHaveText('34 1/2″')
  await dimension(page,'right','24')
  await dimension(page,'left','39')
  await expect(page.locator('path.sm-top')).toHaveCount(1)
  await expect(page.locator('[data-edge="front"] .sm-edge-value')).toHaveText('25 1/2″')
})
