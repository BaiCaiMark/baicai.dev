import { test, expect } from '@playwright/test'
import fs from 'node:fs/promises'

test('two vanity sink centers require X only, stay in one editor, save, reopen and PDF',async({page})=>{
  await page.goto('/tools/site-measure?direct=1')
  await page.getByRole('button',{name:'New project',exact:true}).click()
  await page.getByRole('button',{name:'＋ Rectangle',exact:true}).click()
  await page.locator('[data-edge="back"] [data-dimension]').press('Enter')
  await page.locator('.sm-dimension-editor').getByRole('textbox',{name:'Cabinet size'}).fill('60')
  await page.getByRole('button',{name:'Close dimension editor'}).click()
  await page.locator('[data-edge="right"] [data-dimension]').press('Enter')
  await page.locator('.sm-dimension-editor').getByRole('textbox',{name:'Cabinet size'}).fill('21')
  await page.getByRole('button',{name:'Close dimension editor'}).click()
  await page.getByRole('button',{name:'＋ Sink',exact:true}).click()
  const editor=page.locator('.sm-sink-editor')
  await expect(editor).toBeVisible()
  await expect(editor.getByRole('textbox',{name:'Sink Center distance'})).toBeVisible()
  await expect(editor.getByRole('textbox',{name:/Sink.*Y/})).toHaveCount(0)
  await editor.getByRole('textbox',{name:'Sink Center distance'}).fill('15')
  await editor.getByRole('button',{name:'Add another Sink'}).click()
  await expect(editor.getByRole('button',{name:'Sink 2'})).toHaveAttribute('aria-pressed','true')
  await editor.getByRole('combobox',{name:'Sink X direction'}).selectOption('right')
  await editor.getByRole('textbox',{name:'Sink Center distance'}).fill('15')
  await editor.getByRole('button',{name:'Sink 1'}).click()
  await expect(editor.getByRole('textbox',{name:'Sink Center distance'})).toHaveValue('15')
  await expect(editor.getByRole('combobox',{name:'Sink X direction'})).toHaveValue('left')
  await editor.getByRole('button',{name:'Done',exact:true}).click()
  const pins=page.locator('.sm-direct-sink-pin[data-x-only="true"]')
  await expect(pins).toHaveCount(2)
  await expect(pins.nth(0)).toContainText('S1 15')
  await expect(pins.nth(1)).toContainText('S2 15')
  const pts=await pins.evaluateAll(nodes=>nodes.map(el=>el.getBoundingClientRect().x))
  expect(Math.abs(pts[0]-pts[1])).toBeGreaterThan(60)
  const wait=page.waitForEvent('download')
  await page.getByRole('button',{name:'Backup',exact:true}).click()
  const file=await wait
  const project=JSON.parse(await fs.readFile((await file.path())!,'utf8'))
  const refs=project.areas[0].shapes[0].references
  expect(refs).toHaveLength(2)
  expect(refs.map((r:{x:{input:string};fromX:string})=>[r.x.input,r.fromX])).toEqual([['15','left'],['15','right']])
  expect(refs.every((r:{y:{input:string}})=>r.y.input==='')).toBe(true)
  await expect(page.locator('.sm-save-state')).toHaveText('Saved in this browser')
  await page.reload()
  await page.locator('.sm-recent button').first().click()
  await expect(page.locator('.sm-direct-sink-pin')).toHaveCount(2)
  const waitPdf=page.waitForEvent('download')
  await page.getByRole('button',{name:'Export',exact:true}).click()
  await page.getByRole('button',{name:'Export PDF',exact:true}).click()
  const pdf=await waitPdf
  expect((await fs.readFile((await pdf.path())!)).length).toBeGreaterThan(1000)
})
