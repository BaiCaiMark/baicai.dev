import {test,expect} from '@playwright/test'
import fs from 'node:fs/promises'

test('tap drawing title to rename Part; finished labels retain 60+1 and 21+1.5',async({page})=>{
  await page.goto('/tools/site-measure?direct=1')
  await page.getByRole('button',{name:'New project',exact:true}).click()
  await page.getByRole('button',{name:'＋ Rectangle',exact:true}).click()
  await page.locator('[data-shape] .sm-part-title').click()
  const input=page.getByRole('textbox',{name:'Part name'})
  await expect(input).toBeVisible()
  await input.fill('Master Ensuite Vanity')
  await input.press('Enter')
  await expect(page.locator('[data-shape] .sm-part-title')).toContainText('Master Ensuite Vanity')
  await expect(page.getByRole('button',{name:'Rename Master Ensuite Vanity'})).toBeVisible()
  await page.locator('[data-edge="back"] [data-dimension]').press('Enter')
  await page.locator('.sm-dimension-editor').getByRole('textbox',{name:'Cabinet size'}).fill('60')
  await page.locator('.sm-dimension-editor [aria-label="Right presets"]').getByRole('button',{name:'1',exact:true}).click()
  await page.getByRole('button',{name:'Close dimension editor'}).click()
  await expect(page.locator('[data-edge="back"] .sm-edge-formula')).toHaveText('60 + 1')
  await expect(page.locator('[data-edge="back"] .sm-edge-value')).toHaveText('61″')
  await expect(page.locator('[data-edge="front"] .sm-edge-formula')).toHaveCount(0)
  await page.locator('[data-edge="right"] [data-dimension]').press('Enter')
  await page.locator('.sm-dimension-editor').getByRole('textbox',{name:'Cabinet size'}).fill('21')
  await page.getByRole('button',{name:'Close dimension editor'}).click()
  await expect(page.locator('[data-edge="right"] .sm-edge-formula')).toHaveText('21 + 1.5')
  await expect(page.locator('[data-edge="right"] .sm-edge-value')).toHaveText('22.5″')
  await expect(page.locator('[data-edge="left"] .sm-edge-formula')).toHaveCount(0)
  const wait=page.waitForEvent('download')
  await page.getByRole('button',{name:'Backup',exact:true}).click()
  const file=await wait
  const shape=JSON.parse(await fs.readFile((await file.path())!,'utf8')).areas[0].shapes[0]
  expect(shape.name).toBe('Master Ensuite Vanity')
  expect(shape.dimensions.width.input).toBe('60')
  expect(shape.dimensions.height.input).toBe('21')
  expect(shape.allowances.right.input).toBe('1')
  expect(shape.allowances.front.input).toBe('1.5')
  await expect(page.locator('.sm-save-state')).toHaveText('Saved in this browser')
  await page.reload()
  await page.locator('.sm-recent button').first().click()
  await expect(page.locator('[data-shape] .sm-part-title')).toContainText('Master Ensuite Vanity')
  await expect(page.locator('[data-edge="back"] .sm-edge-formula')).toHaveText('60 + 1')
})

test('toolbar rename handles cancel and one committed change; formula follows live allowance edits',async({page})=>{
  await page.goto('/tools/site-measure?direct=1')
  await page.getByRole('button',{name:'New project',exact:true}).click()
  await page.getByRole('button',{name:'＋ Rectangle',exact:true}).click()
  await page.getByRole('button',{name:'Rename Kitchen 1'}).click()
  const input=page.getByRole('textbox',{name:'Part name'})
  await input.fill('Accidental rename')
  await input.press('Escape')
  await expect(page.locator('[data-shape] .sm-part-title')).toHaveText('Kitchen 1')
  await page.getByRole('button',{name:'Rename Kitchen 1'}).click()
  await input.fill('Powder Room')
  await page.getByRole('button',{name:'Save part name'}).click()
  await expect(page.locator('[data-shape] .sm-part-title')).toHaveText('Powder Room')
  await page.locator('[data-edge="back"] [data-dimension]').press('Enter')
  await page.locator('.sm-dimension-editor').getByRole('textbox',{name:'Cabinet size'}).fill('60')
  await page.locator('.sm-dimension-editor [aria-label="Right presets"]').getByRole('button',{name:'1',exact:true}).click()
  await expect(page.locator('.sm-dimension-editor')).toBeVisible()
  await expect(page.locator('[data-edge="back"] .sm-edge-formula')).toHaveText('60 + 1')
  await page.locator('.sm-dimension-editor [aria-label="Right presets"]').getByRole('button',{name:'1.5',exact:true}).click()
  await expect(page.locator('[data-edge="back"] .sm-edge-formula')).toHaveText('60 + 1.5')
  await expect(page.locator('[data-edge="back"] .sm-edge-value')).toHaveText('61.5″')
})
