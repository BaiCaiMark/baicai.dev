test('selected part drags from its interior; Ortho keeps the alignment without a move handle',async({page})=>{
  await page.goto('/tools/site-measure')
  await page.getByRole('button',{name:'Try sample Kitchen',exact:true}).click()
  const part=page.locator('[data-shape]').first()
  const transform=async()=>part.getAttribute('transform')
  const position=async()=>part.evaluate(el=>{
    const path=el.querySelector<SVGPathElement>('path.sm-top')!
    const q=new DOMPoint(55,55).matrixTransform(path.getScreenCTM()!)
    return{x:q.x,y:q.y}
  })
  const move=async(dx:number,dy:number)=>{
    const q=await position()
    await page.mouse.move(q.x,q.y)
    await page.mouse.down()
    await page.mouse.move(q.x+dx,q.y+dy,{steps:10})
    await page.mouse.up()
  }
  const old=await transform()
  await page.getByRole('button',{name:'Snap',exact:true}).click()
  await move(55,25)
  const moved=await transform()
  expect(moved).not.toBe(old)
  await page.getByRole('button',{name:'Ortho',exact:true}).click()
  const beforeY=Number(/translate\(([-\d.]+) ([-\d.]+)\)/.exec(moved!)![2])
  await move(50,14)
  const changed=await transform()
  const afterY=Number(/translate\(([-\d.]+) ([-\d.]+)\)/.exec(changed!)![2])
  expect(afterY).toBeCloseTo(beforeY,5)
  await page.getByRole('button',{name:'Undo',exact:true}).click()
  await expect(part).toHaveAttribute('transform',moved!)
})
